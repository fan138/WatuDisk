def tips_for_disk(level: str, seed: int = 0, count: int = 3) -> list[str]:
    """按盘况挑选一组护盘建议（确定性轮换，避免每次体检都一样）。

    Args:
        level: healthy / warning / danger。
        seed: 轮换种子（可用体检次数，让建议每轮更新）。
        count: 返回条数。
    """
    import random

    pool = list(GENERAL)
    rng = random.Random(seed)
    picked = rng.sample(pool, min(count - 1, len(pool)))
    tail_pool = {"healthy": KEEP, "warning": INTERVENE, "danger": URGENT}.get(level, KEEP)
    picked.append((level, tail_pool[seed % len(tail_pool)]))
    return [f"「{name}」{text}" for name, text in picked]


def total_count() -> int:
    """建议条数（自检用）。"""
    return len(GENERAL) + len(KEEP) + len(INTERVENE) + len(URGENT)
