def pick(category: str) -> tuple[str, str]:
    """按分类随机抽一条（标题, 文案），尽量不与上一条重复。

    Returns:
        (title, text)；分类未知时返回通用健康文案。
    """
    pool = {
        "ok": CHECK_OK,
        "warn": CHECK_WARN,
        "danger": CHECK_DANGER,
        "space_low": SPACE_LOW,
        "space_critical": SPACE_CRITICAL,
        "hot": TEMP_HOT,
        "boot": BOOT_GREETING,
    }.get(category) or CHECK_OK
    text = random.choice(pool)
    try:
        store = get_store()
        last = str(store.get_setting("last_tender_text") or "")
        if text == last and len(pool) > 1:
            text = random.choice([t for t in pool if t != text])
        store.set_setting("last_tender_text", text)
    except Exception:
        pass
    return _TITLES.get(category, "体检报告"), text


def boot_greeting() -> str:
    """按时段的专属开机问候（早晨/午后/夜晚各取所宜）。"""
    hour = datetime.now().hour
    if 5 <= hour < 12:
        return random.choice(BOOT_GREETING[:7])
    if 12 <= hour < 19:
        return random.choice(BOOT_GREETING[7:14])
    return random.choice(BOOT_GREETING[14:])


def total_count() -> int:
    """文案总数（自检用）。"""
    return sum(
        len(lst)
        for lst in (CHECK_OK, CHECK_WARN, CHECK_DANGER, SPACE_LOW, SPACE_CRITICAL, TEMP_HOT, BOOT_GREETING)
    )
